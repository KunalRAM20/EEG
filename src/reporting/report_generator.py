DISCLAIMER = (
    "This report is generated by an automated clinical DECISION-SUPPORT system and is "
    "intended to assist, not replace, a qualified physician. The evidence tier "
    "uses EEG only. Supplemental modalities are contextual and are not model "
    "inputs unless a future report explicitly states otherwise. The five-level "
    "grade is a calibrated-probability tier, not a validated clinical seizure-"
    "severity scale. Final diagnosis and treatment decisions rest with the "
    "reviewing clinician."
)


def _label(feature: str) -> str:
    return FEATURE_LABELS.get(feature, feature)


# ASCII only: this block is embedded verbatim in the latin-1 PDF export, where
